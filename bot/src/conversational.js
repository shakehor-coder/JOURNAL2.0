import { getRandomItem, dailyMotivations, itJokes, excuses } from "./funFeatures.js";

// История диалогов по chatId: Map<number, Array<{ role: string, text: string }>>
const chatHistories = new Map();

function getHistory(chatId) {
  if (!chatHistories.has(chatId)) {
    chatHistories.set(chatId, []);
  }
  return chatHistories.get(chatId);
}

function addToHistory(chatId, role, text) {
  const history = getHistory(chatId);
  history.push({ role, text, time: Date.now() });
  if (history.length > 10) history.shift();
}

/**
 * Интеллектуальный разговорный генератор ответов
 */
export async function generateChatResponse(chatId, userText) {
  const clean = (userText || "").trim().toLowerCase();
  addToHistory(chatId, "user", userText);

  // 1. Приветствия
  if (/^(привет|хай|ку|салам|здравствуй|добрый (день|вечер|утро)|hello|hi|hey)/i.test(clean)) {
    const greetings = [
      "Привет-привет! 👋 Рад тебя видеть! Как настроение? Готов поболтать или глянем расписание в Клауде?",
      "Хэй! Салют! 🚀 Я на связи и полон энергии. Чем займёмся сегодня?",
      "Здорово! ✌️ Как твои пары и домашки? Рассказывай, что интересного!",
      "Приветствую, будущий сеньор-разработчик! 💻 Что нового на просторах колледжа?"
    ];
    const reply = getRandomItem(greetings);
    addToHistory(chatId, "bot", reply);
    return reply;
  }

  // 2. Как дела?
  if (/как (дела|ты|жизнь|оно|делишки|настроение)/i.test(clean)) {
    const replies = [
      "У меня всё компилируется без ворнингов! ⚡ Пью виртуальный кофе и готов помочь тебе с расписанием или просто поднять настроение. А у тебя как день проходит?",
      "Отлично! Мои транзисторы урчат от удовольствия. 🤖 Сижу вот, жду твоих сообщений. Ты как сам?",
      "На высоте! Ни одного segmentation fault за сегодня. Как учеба? Преподаватели не сильно нагружают? 😄",
      "Полный порядок! Готов хоть к защите диплома, хоть к игре в камень-ножницы-бумага! 🎲"
    ];
    const reply = getRandomItem(replies);
    addToHistory(chatId, "bot", reply);
    return reply;
  }

  // 3. Что делаешь?
  if (/что (делаешь|поделываешь|мутишь)/i.test(clean)) {
    const replies = [
      "Слежу за серверами Клауда, разминаю алгоритмические мышцы и жду интересных вопросов от тебя! 🚀",
      "Оптимизирую ответы на лету и придумываю новые отмазки для пар. Хочешь подкину одну? Нажми «🎭 Отмазка»!",
      "Думаю о вечном... Например, почему в сутках всего 24 часа, а домашек задают на все 48! 😅"
    ];
    const reply = getRandomItem(replies);
    addToHistory(chatId, "bot", reply);
    return reply;
  }

  // 4. Кто ты / расскажи о себе
  if (/(кто ты|что ты такое|расскажи о себе|что ты умеешь|какие возможности)/i.test(clean)) {
    const reply = 
      "Я — **FlipClip**! 🤖 Твой умный и веселый бот-собеседник!\n\n" +
      "Вот что я умею:\n" +
      "💬 **Общаться по душам**: отвечу на твои мысли, поддержу диалог, пошучу или выслушаю.\n" +
      "🎓 **Связь с Клаудом ТОП**: по твоему API-ключу могу показать расписание, оценки, домашки и коины!\n" +
      "🎲 **Игры и развлечения**: Камень-Ножницы-Бумага, Угадай число, Дайс, IT-викторина.\n" +
      "🔮 **Шар судьбы**: предскажет, сдашь ли ты лабу или экзамен.\n" +
      "🎭 **Генератор отмазок**: если вдруг проспал пару.\n" +
      "💡 **Мотивация и анекдоты**: чтобы не выгореть во время сессии.\n\n" +
      "Выбирай кнопку в меню или просто пиши мне текст!";
    addToHistory(chatId, "bot", reply);
    return reply;
  }

  // 5. Усталость / лень / не хочу учиться
  if (/(устал|лень|не хочу (учиться|на пары|делать)|задолбало|выгорел|спать хочу|депрессия)/i.test(clean)) {
    const replies = [
      "Ох, прекрасно тебя понимаю! 🛋️ Учёба в IT — это марафон, а не спринт. Сделай паузу на 15 минут, завари чайку, подыши свежим воздухом. А потом потихоньку разберемся с задачами!",
      "Знакомо каждому студенту! 😴 Держи порцию мотивации: " + getRandomItem(dailyMotivations) + "\n\nА если совсем лень идти на пару — глянь «🎭 Генератор отмазок», там есть шедевры!",
      "Главное — не перегружай оперативку своего мозга! Попробуй метод Помодоро: 25 минут кодишь — 5 минут залипаешь в мемы. Проверено поколениями джунов! ☕"
    ];
    const reply = getRandomItem(replies);
    addToHistory(chatId, "bot", reply);
    return reply;
  }

  // 6. Экзамен / зачет / лаба
  if (/(экзамен|зачет|сессия|лаба|контрольная|дедлайн)/i.test(clean)) {
    const replies = [
      "Спокойствие, только спокойствие! 🧘‍♂️ Главное правило сдачи лаб: если код работает — не трогай его руками перед показом преподавателю!",
      "Держи кулачки! ✊ Хочешь спросить у нашего магического шара, сдашь ли ты? Напиши «шар» или задай прямой вопрос, например: «шар сдам ли я экзамен?»",
      "Дедлайн — это лучший источник вдохновения! ⏳ Соберись, налей энергетика или кофе, и покажи этой лабе, кто тут главный программист!"
    ];
    const reply = getRandomItem(replies);
    addToHistory(chatId, "bot", reply);
    return reply;
  }

  // 7. Шутка / анекдот
  if (/(шутк|анекдот|рассмеши|прикол|мем)/i.test(clean)) {
    const joke = getRandomItem(itJokes);
    addToHistory(chatId, "bot", joke);
    return joke;
  }

  // 8. Благодарность
  if (/(спасибо|от души|благодарю|спс|ты лучший|красава|молодец|топ)/i.test(clean)) {
    const replies = [
      "Всегда рад помочь! 😎 Ты тоже топ! Если что — я всегда тут.",
      "Обращайся в любое время! Мне только в радость поболтать с умным человеком. 🦾",
      "Ради этого мои алгоритмы и трудятся! Обращайся ещё! ✨"
    ];
    const reply = getRandomItem(replies);
    addToHistory(chatId, "bot", reply);
    return reply;
  }

  // 9. О программировании и языках
  if (/(python|javascript|c\+\+|c#|react|java|go|rust|php|html|css)/i.test(clean)) {
    const replies = [
      "О, уважаю выбор технологий! 💻 Главное помнить: идеального языка нет, лучший тот, на котором решается задача (и за который платят хорошую зарплату!).",
      "Технологии — это мощь! Главное не утонуть в выборе фреймворков и писать чистый, понятный код. Практика решает всё! 🚀",
      "Хороший стек! Если делаешь проект на нем — доводи до конца, это будет мощнейший кейс в твое резюме! 🏆"
    ];
    const reply = getRandomItem(replies);
    addToHistory(chatId, "bot", reply);
    return reply;
  }

  // 10. Шар судьбы через текст ("шар ...")
  if (/^шар\b/i.test(clean) || clean.endsWith("?")) {
    // Если вопрос похож на гадание
    if (clean.endsWith("?") && (clean.includes("ли") || clean.includes("будет") || clean.includes("стоит") || clean.startsWith("шар"))) {
      const ball = getRandomItem([
        "🔮 Шар судьбы говорит: **Определённо да!** Звёзды и компилятор на твоей стороне! ✨",
        "🔮 Шар судьбы говорит: **Шансы 50 на 50.** Всё зависит от твоей уверенности перед преподом! ⚡",
        "🔮 Шар судьбы говорит: **Лучше не стоит.** Риск слишком велик, перепроверь код! 🛑",
        "🔮 Шар судьбы говорит: **100% успех!** Смело иди вперёд! 🚀",
        "🔮 Шар судьбы говорит: **Знаки туманны...** Спроси старосту или переспроси позже! 🌫️"
      ]);
      addToHistory(chatId, "bot", ball);
      return ball;
    }
  }

  // 11. Отмазка через текст
  if (/отмазк|почему опоздал|оправдани/i.test(clean)) {
    const excuse = "🎭 **Отмазка дня:**\n" + getRandomItem(excuses);
    addToHistory(chatId, "bot", excuse);
    return excuse;
  }

  // 12. Мотивация
  if (/мотивац|поддержи|грустн|тоск/i.test(clean)) {
    const mot = "🌟 **Специально для тебя:**\n" + getRandomItem(dailyMotivations);
    addToHistory(chatId, "bot", mot);
    return mot;
  }

  // 13. Универсальный интеллектуальный разговорный ответ
  const generalReplies = [
    `Хм, интересная мысль! 🤔 А что ты сам думаешь по этому поводу? Расскажи подробнее!`,
    `Звучит любопытно! Записал это в свои нейронные логи. 📝 Как твои дела сегодня в колледже?`,
    `Согласен с тобой на все 100%! Кстати, не забывай делать перерывы между кодингом и парами ☕`,
    `Ого, вот это поворот! Ты умеешь удивить. О чём ещё думаешь прямо сейчас?`,
    `В точку! Мне нравится ход твоих мыслей. Хочешь сыграть в игру или посмотрим расписание? 🎮`,
    `Интересный взгляд на вещи. Мой цифровой интеллект полностью одобряет! 🤖 Чем сейчас занят?`
  ];

  const reply = getRandomItem(generalReplies);
  addToHistory(chatId, "bot", reply);
  return reply;
}
